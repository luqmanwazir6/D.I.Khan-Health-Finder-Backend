import { ApiError } from './ApiError.js';
import { escapeRegex } from './escapeRegex.js';
import { buildPaginationMeta } from './apiResponse.js';
import { PAGINATION } from '../config/constants.js';

/**
 * Builds standard pagination, sorting, search, and filtering for Mongoose queries.
 *
 * @param {object} params
 * @param {object} params.query - Request query object (req.query)
 * @param {Array<string>} params.allowedSortFields - Whitelisted fields allowed for sorting
 * @param {string} [params.defaultSort='-createdAt'] - Fallback sort string
 * @param {Array<string>} [params.searchFields=[]] - Model fields to test against `q` parameter
 * @param {object} [params.baseFilter={}] - Base filter conditions to enforce (e.g. { isActive: true })
 * @returns {{ filter: object, sort: object, page: number, limit: number, skip: number }}
 */
export function buildQuery({
  query = {},
  allowedSortFields = ['createdAt'],
  defaultSort = '-createdAt',
  searchFields = [],
  baseFilter = {}
}) {
  // 1. Pagination values
  let page = parseInt(query.page, 10);
  if (isNaN(page) || page < 1) {
    page = PAGINATION.DEFAULT_PAGE;
  }

  let limit = parseInt(query.limit, 10);
  if (isNaN(limit) || limit < 1) {
    limit = PAGINATION.DEFAULT_LIMIT;
  } else if (limit > PAGINATION.MAX_LIMIT) {
    limit = PAGINATION.MAX_LIMIT;
  }

  const skip = (page - 1) * limit;

  // 2. Sorting
  const sortString = query.sort || defaultSort;
  const sort = {};

  if (sortString) {
    const sortParts = sortString.split(',').map((s) => s.trim()).filter(Boolean);

    for (const part of sortParts) {
      const isDesc = part.startsWith('-');
      const field = isDesc ? part.substring(1) : part;

      if (!allowedSortFields.includes(field)) {
        throw ApiError.badRequest(
          `Invalid sort field: '${field}'. Allowed fields: [${allowedSortFields.join(', ')}]`
        );
      }

      sort[field] = isDesc ? -1 : 1;
    }
  }

  // 3. Base Filtering
  const filter = { ...baseFilter };

  // 4. Free-text Search `q`
  if (query.q && typeof query.q === 'string' && query.q.trim() && searchFields.length > 0) {
    const escaped = escapeRegex(query.q.trim());
    const regex = new RegExp(escaped, 'i');

    const searchConditions = searchFields.map((field) => ({
      [field]: regex
    }));

    if (filter.$or) {
      filter.$and = [{ $or: filter.$or }, { $or: searchConditions }];
      delete filter.$or;
    } else {
      filter.$or = searchConditions;
    }
  }

  return {
    filter,
    sort,
    page,
    limit,
    skip
  };
}

/**
 * Executes a paginated Mongoose query and returns documents with pagination metadata.
 *
 * @param {import('mongoose').Model} Model
 * @param {object} queryOptions - Generated by buildQuery
 * @param {string|object} [populate] - Optional populate configuration
 * @param {string} [select] - Optional field projection
 * @returns {Promise<{ docs: Array<any>, meta: object }>}
 */
export async function executePaginatedQuery(
  Model,
  { filter, sort, page, limit, skip },
  populate = null,
  select = null
) {
  let queryPromise = Model.find(filter).sort(sort).skip(skip).limit(limit);

  if (select) {
    queryPromise = queryPromise.select(select);
  }

  if (populate) {
    queryPromise = queryPromise.populate(populate);
  }

  const [docs, total] = await Promise.all([
    queryPromise.exec(),
    Model.countDocuments(filter).exec()
  ]);

  const meta = buildPaginationMeta(page, limit, total);

  return {
    docs,
    meta
  };
}

export default {
  buildQuery,
  executePaginatedQuery
};
